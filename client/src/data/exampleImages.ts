// Example images data structure with gender, style, and prompts
export interface ExampleImage {
  id: number;
  url: string;
  badge: string | null;
  gender: "man" | "woman" | "both"; // Which gender this image is for
  styles: string[]; // Which styles this image represents (formal, casual, elegant, professional)
  backgrounds: string[]; // Which backgrounds this image works with (office, studio, city, nature, interior)
  prompt: string; // Specific prompt for this image style
  // Store the original filename for matching logic
  filename: string;
}

// Known background values
const KNOWN_BACKGROUNDS = ["office", "studio", "city", "nature", "interior"];

// Known style values
const KNOWN_STYLES = ["formal", "casual", "elegant", "professional"];

// Parse filename to extract attributes
function parseFilename(filename: string): {
  gender: "man" | "woman" | null;
  backgrounds: string[];
  styles: string[];
} {
  const name = filename.replace(/\.[^/.]+$/, ""); // Remove extension
  const parts = name.split("_");

  let gender: "man" | "woman" | null = null;
  const foundBackgrounds: string[] = [];
  const foundStyles: string[] = [];

  for (const part of parts) {
    if (part === "man" || part === "woman") {
      gender = part;
    } else if (KNOWN_BACKGROUNDS.includes(part)) {
      foundBackgrounds.push(part);
    } else if (KNOWN_STYLES.includes(part)) {
      foundStyles.push(part);
    }
  }

  return { gender, backgrounds: foundBackgrounds, styles: foundStyles };
}

