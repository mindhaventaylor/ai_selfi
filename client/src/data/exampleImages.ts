// Helper function to filter images based on filename matching
// Images show if ANY combination of selected filters matches the filename
// Gender is mutually exclusive (man/woman cannot overlap)
// Example: "4_man_neutral_studio_casual_professional" will show if:
// - man is selected (alone)
// - man and neutral are selected
// - man and studio are selected
// - man, neutral, and casual are selected
// - etc. (any combination where at least one selected filter matches)
export function filterExampleImages(
  images: ExampleImage[],
  gender: "man" | "woman",
  selectedStyles: string[],
  selectedBackgrounds: string[]
): ExampleImage[] {
  return images.filter((img) => {
    // Gender must match (mutually exclusive)
    if (img.gender !== gender) {
      return false;
    }

    // If no style/background filters are selected, show all images for the selected gender
    if (selectedStyles.length === 0 && selectedBackgrounds.length === 0) {
      return true;
    }

    // Get all selected filter values (styles + backgrounds)
    const allSelectedFilters = [...selectedStyles, ...selectedBackgrounds];
    
    // Get all filter values from the image (styles + backgrounds)
    const imageFilters = [...img.styles, ...img.backgrounds];
    
    // Check if ANY selected filter matches the image's filters
    // This means if user selects "neutral", show all images that have "neutral" in their filename
    // If user selects "neutral" and "casual", show images that have at least one of "neutral" or "casual"
    const hasMatchingFilter = allSelectedFilters.some((selectedFilter) =>
      imageFilters.includes(selectedFilter)
    );

    return hasMatchingFilter;
  });
}
